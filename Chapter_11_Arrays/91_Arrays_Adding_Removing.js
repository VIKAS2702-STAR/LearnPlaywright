let arr = [1, 2, 3];
console.log( arr );

// Adding new element at the end
arr.push( 4 );
console.log( arr );

//Removing an element from the end
arr.pop();
console.log( arr );

// Adding multiple element at the end
arr.push( 5, 6 );
console.log( arr );

// Adding an element at the begining
arr.unshift( 0 );
console.log( arr );

// Removing an element from the begining
arr.shift();
console.log( arr );