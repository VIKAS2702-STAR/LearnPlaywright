var name = "vikas;"
var firstName = "Vikas;"
var lastName =  "Prajapatai;" //camel case

var first_name =  "Vikas;" //Snake Case

// PascalCase - Used for class names, constructors, enums
var FirstName = "Vikas;"
var UserProfile = "Prajapati;"

// UPPER_SNAKE_CASE / SCREAMING_SNAKE_CASE - Used for constants
var MAX_SIZE = 100;
var PI_VALUE = 3.14;
var DATABASE_URL = "localhost;"

// Hungarian notation - Prefix indicates type (less common now)
var strName = "Vikas;"
var intAge = 25;
var bIsActive = true;
var arrNames = ["Vikas", "Amit"];

// Single character identifiers (used in loops/math)
var i = 0;
var x = 10;
var _ = "underscore only;"

// Mixed examples for contrast
var userName = "camelCase;"       // variable, function
var UserName = "PascalCase;"      // class, constructor
var user_name = "snake_case;"     // variable, Python style
var USER_NAME = "SCREAMING_SNAKE;" // constant

// kebab-case (hyphen-separated) - NOT valid in JavaScript identifiers, but used in CSS/HTML
// var first-name = "Vikas";  // This would cause a syntax error
var cssClassName = "first-name"; // Use camelCase in JS, kebab-case in CSS

// Train-Case / HTTP-Header-Case (capitalized words with hyphens)
var httpHeaderExample = "Content-Type"; // Used in HTTP headers

// flatcase / lowercase - all lowercase, no separators
var firstname = "Vikas;"
var username = "vikasprajapati;"

// COBOL-CASE / MACRO_CASE with hyphens - uppercase with hyphens
// Not valid for JS variables, but used in constants/namespaces in other languages
var envVarExample = "NODE_ENV"; // Often seen in environment variables (screaming snake in practice)

// camelCase variations with numbers (legal but avoid starting with number)
var name1 = "Vikas;"
var first1Name = "Vikas;"
var userName2 = "Prajapati;"

// Dromedary case = camelCase starting with lowercase (most common)
var dromedaryCase = "startsLower;"

// PascalCase is sometimes called UpperCamelCase or StudlyCase
var UpperCamelCase = "PascalCase synonym;"

// __double_leading_underscore (name mangling in Python style, avoid in JS)
var __privateVar = "convention for internal;"

// $dollarCase - often used for generated code or special variables
var $name = "jQuery style;"
var $$root = "double dollar;"

