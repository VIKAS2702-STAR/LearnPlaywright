let fruit = "Banana";
switch ( fruit ) {
    case "Apple":
        console.log( "Apple Selected" );
    case "Banana":
        console.log( "Banana Selected" );
    case "Cherry":
        console.log( "Cherry Selected" );
    case "Date":
        console.log( "Date Selected" );
    default:
        console.log( "Default Reached" );
}