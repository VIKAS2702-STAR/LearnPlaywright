// Maximum number between two numbers using ternary operator

let a = 10;
let b = 20;
let max = a > b ? a : b;
console.log( "The maximum number between", a, "and", b, "is:", max );

// Another example with negative numbers
let x = -5;
let y = -15;
let maxNegative = x > y ? x : y;
console.log( "The maximum number between", x, "and", y, "is:", maxNegative );



